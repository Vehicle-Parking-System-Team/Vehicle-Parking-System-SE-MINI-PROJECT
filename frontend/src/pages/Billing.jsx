import { useCallback, useEffect, useRef, useState } from 'react'
import { useAuth } from '../context/useAuth'
import { parseApiError } from '../utils/apiErrors'
import './ParkingOperations.css'

const money = (amount, currency = 'INR') => new Intl.NumberFormat(undefined, { style: 'currency', currency }).format(amount)

async function api(fetchWithAuth, url, options) {
  const response = await fetchWithAuth(url, options)
  const data = await response.json().catch(() => null)
  if (!response.ok) throw new Error(parseApiError(data).message || `Request failed (${response.status}).`)
  return data
}

export async function printReceipt(fetchWithAuth, receipt) {
  // Open synchronously from the click handler so popup blockers do not discard it.
  const preview = window.open('', '_blank')
  if (!preview) throw new Error('Allow popups for this site to print a receipt.')
  try {
    preview.document.title = 'Loading receipt…'
    const response = await fetchWithAuth(receipt.print_url)
    if (!response.ok) throw new Error('Unable to load the printable receipt.')
    const html = await response.text()
    const document = preview.document
    document.open()
    document.write(html)
    document.close()
    // The HTML is generated by the authenticated server receipt template.
    preview.focus()
    if (document.readyState === 'complete') preview.print()
    else preview.addEventListener('load', () => preview.print(), { once: true })
  } catch (error) {
    preview.close()
    throw error
  }
}

function Settlement({ receipt, fetchWithAuth, onSaved, onClose }) {
  const dialog = useRef(null)
  const [status, setStatus] = useState('Paid')
  const [method, setMethod] = useState('Cash')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  useEffect(() => {
    const previous = document.activeElement
    dialog.current?.querySelector('select')?.focus()
    return () => previous?.focus?.()
  }, [])

  async function submit(event) {
    event.preventDefault()
    setBusy(true)
    setError('')
    try {
      const saved = await api(fetchWithAuth, `/api/parking/receipts/${receipt.receipt_id}/payment/`, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ payment_status: status, payment_method: status === 'Paid' ? method : null,
          payment_amount: status === 'Paid' ? receipt.total_fee : '0.00' }),
      })
      onSaved(saved)
    } catch (e) { setError(e.message) } finally { setBusy(false) }
  }

  return <div className="billing-overlay" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose() }}>
    <div ref={dialog} className="billing-dialog parking-result" role="dialog" aria-modal="true" aria-labelledby="settlement-title" onKeyDown={(e) => {
      if (e.key === 'Escape') onClose()
      if (e.key === 'Tab') {
        const items = [...dialog.current.querySelectorAll('select:not([disabled]), button:not([disabled])')]
        if (e.shiftKey && document.activeElement === items[0]) { e.preventDefault(); items.at(-1).focus() }
        else if (!e.shiftKey && document.activeElement === items.at(-1)) { e.preventDefault(); items[0].focus() }
      }
    }}>
      <h2 id="settlement-title">Settle {receipt.invoice_number}</h2>
      <p>{receipt.registration_number} · Amount due {money(receipt.total_fee, receipt.currency)}</p>
      <form className="parking-form" onSubmit={submit}>
        <label>Settlement<select value={status} onChange={(e) => setStatus(e.target.value)}><option value="Paid">Record payment</option><option value="Waived">Waive fee</option></select></label>
        {status === 'Paid' && <label>Payment method<select value={method} onChange={(e) => setMethod(e.target.value)}><option>Cash</option><option>Card</option><option>UPI</option></select></label>}
        {status === 'Waived' && <p>Only authorized staff may waive this fee. This action is recorded in the audit log.</p>}
        {error && <p role="alert">{error}</p>}
        <button disabled={busy}>{busy ? 'Saving…' : status === 'Paid' ? 'Record payment' : 'Confirm waiver'}</button>
        <button type="button" onClick={onClose}>Cancel</button>
      </form>
    </div>
  </div>
}

export function ReceiptCard({ receipt, fetchWithAuth, canManage, onSaved }) {
  const [settling, setSettling] = useState(false)
  const [error, setError] = useState('')
  return <article className="parking-result">
    <h2>{receipt.invoice_number}</h2>
    <p>{receipt.registration_number} · {new Date(receipt.check_out_time).toLocaleString()} · {receipt.payment_status}</p>
    <p>Bay {receipt.slot_number} · {money(receipt.total_fee, receipt.currency)}</p>
    <button type="button" onClick={async () => { setError(''); try { await printReceipt(fetchWithAuth, receipt) } catch (e) { setError(e.message) } }}>Print receipt</button>
    {canManage && receipt.payment_status === 'Pending' && <button type="button" onClick={() => setSettling(true)}>Settle payment</button>}
    {error && <p role="alert">{error}</p>}
    {settling && <Settlement receipt={receipt} fetchWithAuth={fetchWithAuth} onSaved={(saved) => { setSettling(false); onSaved(saved) }} onClose={() => setSettling(false)} />}
  </article>
}

export function ReceiptsPage() {
  const { fetchWithAuth, user } = useAuth()
  const [result, setResult] = useState(null)
  const [url, setUrl] = useState('/api/parking/receipts/')
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)
  const [retry, setRetry] = useState(0)
  useEffect(() => {
    let active = true
    api(fetchWithAuth, url).then((data) => { if (active) { setResult(data); setError('') } })
      .catch((e) => { if (active) setError(e.message) })
      .finally(() => { if (active) setLoading(false) })
    return () => { active = false }
  }, [fetchWithAuth, url, retry])
  function load(next) { setLoading(true); setUrl(next) }
  return <section className="parking-operations">
    <header className="bay-page-heading"><h1>Receipts</h1></header>
    {loading && <p role="status">Loading receipts…</p>}
    {error && <p role="alert">{error} <button onClick={() => { setLoading(true); setRetry((n) => n + 1) }}>Retry</button></p>}
    {!loading && result?.count === 0 && <p>No receipts yet.</p>}
    {result?.results?.map((receipt) => <ReceiptCard key={receipt.receipt_id} receipt={receipt} fetchWithAuth={fetchWithAuth} canManage={user?.role === 'Admin' || user?.role === 'Operator'} onSaved={(saved) => setResult((old) => ({ ...old, results: old.results.map((r) => r.receipt_id === saved.receipt_id ? saved : r) }))} />)}
    {result && <nav aria-label="Receipt pages"><button disabled={!result.previous || loading} onClick={() => load(result.previous)}>Previous</button> <button disabled={!result.next || loading} onClick={() => load(result.next)}>Next</button></nav>}
  </section>
}

export function TariffsPage() {
  const { fetchWithAuth } = useAuth()
  const [rates, setRates] = useState([])
  const [selected, setSelected] = useState('Two-Wheeler')
  const selectedRef = useRef('Two-Wheeler')
  const [form, setForm] = useState({ hourly_rate: '', vehicle_multiplier: '1.00', grace_period_minutes: '15', penalty_fee: '0.00' })
  const [error, setError] = useState('')
  const [busy, setBusy] = useState(false)
  const load = useCallback(async () => {
    try {
      const loaded = await api(fetchWithAuth, '/api/v1/rates/')
      setRates(loaded)
      setForm((current) => {
        const pristine = current.hourly_rate === '' && current.vehicle_multiplier === '1.00' &&
          current.grace_period_minutes === '15' && current.penalty_fee === '0.00'
        return pristine ? (loaded.find((rate) => rate.vehicle_type === selectedRef.current) || current) : current
      })
      setError('')
    } catch (e) { setError(e.message) }
  }, [fetchWithAuth])
  useEffect(() => { load() }, [load])
  const existing = rates.find((r) => r.vehicle_type === selected)
  function choose(type) { selectedRef.current = type; setSelected(type); const rate = rates.find((r) => r.vehicle_type === type); setForm(rate || { hourly_rate: '', vehicle_multiplier: '1.00', grace_period_minutes: '15', penalty_fee: '0.00' }) }
  async function save(e) {
    e.preventDefault(); setBusy(true); setError('')
    try {
      await api(fetchWithAuth, existing ? `/api/v1/rates/${existing.id}/` : '/api/v1/rates/', {
        method: existing ? 'PATCH' : 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ ...form, vehicle_type: selected, grace_period_minutes: Number(form.grace_period_minutes) }),
      }); await load()
    } catch (e) { setError(e.message) } finally { setBusy(false) }
  }
  return <section className="parking-operations"><header className="bay-page-heading"><h1>Tariff configuration</h1></header>
    <div className="parking-result"><h2>Configured rates</h2>{rates.map((rate) => <p key={rate.id}>{rate.vehicle_type}: {money(rate.hourly_rate)}/hour · {rate.vehicle_multiplier}× · {rate.grace_period_minutes} min grace <button onClick={() => choose(rate.vehicle_type)}>Edit</button></p>)}</div>
    <form className="parking-form parking-result" onSubmit={save}>
      <label>Vehicle class<select value={selected} onChange={(e) => choose(e.target.value)}>{['Two-Wheeler', 'Compact', 'SUV', 'EV Charging'].map((type) => <option key={type}>{type}</option>)}</select></label>
      <label>Hourly rate<input type="number" min="0" step="0.01" required value={form.hourly_rate} onChange={(e) => setForm({ ...form, hourly_rate: e.target.value })} /></label>
      <label>Vehicle multiplier<input type="number" min="0" step="0.01" required value={form.vehicle_multiplier} onChange={(e) => setForm({ ...form, vehicle_multiplier: e.target.value })} /></label>
      <label>Grace period (minutes)<input type="number" min="0" step="1" required value={form.grace_period_minutes} onChange={(e) => setForm({ ...form, grace_period_minutes: e.target.value })} /></label>
      <label>Penalty fee<input type="number" min="0" step="0.01" required value={form.penalty_fee} onChange={(e) => setForm({ ...form, penalty_fee: e.target.value })} /></label>
      {error && <p role="alert">{error} <button type="button" onClick={load}>Reload</button></p>}
      <button disabled={busy}>{busy ? 'Saving…' : existing ? 'Update tariff' : 'Create tariff'}</button>
    </form>
  </section>
}
